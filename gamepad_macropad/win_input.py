"""Win32 input injection (SendInput) and small cursor/window helpers.

This is the only module that injects input. Everything goes through
``SendInput``; every event we emit is tagged with :data:`INJECT_TAG` in
``dwExtraInfo`` so our own low-level hooks can ignore it while recording.
"""

from __future__ import annotations

import ctypes
import sys
import threading
import time
from ctypes import wintypes
from typing import Iterable

from . import keys

if sys.platform != "win32":  # pragma: no cover - module is Windows only
    raise ImportError("win_input is only available on Windows")

user32 = ctypes.WinDLL("user32", use_last_error=True)
kernel32 = ctypes.WinDLL("kernel32", use_last_error=True)
winmm = ctypes.WinDLL("winmm", use_last_error=True)

INJECT_TAG = 0x47504D50  # "GPMP" - marks input generated by this app

INPUT_MOUSE = 0
INPUT_KEYBOARD = 1

KEYEVENTF_KEYUP = 0x0002
KEYEVENTF_UNICODE = 0x0004
KEYEVENTF_EXTENDEDKEY = 0x0001

MOUSEEVENTF_MOVE = 0x0001
MOUSEEVENTF_LEFTDOWN = 0x0002
MOUSEEVENTF_LEFTUP = 0x0004
MOUSEEVENTF_RIGHTDOWN = 0x0008
MOUSEEVENTF_RIGHTUP = 0x0010
MOUSEEVENTF_MIDDLEDOWN = 0x0020
MOUSEEVENTF_MIDDLEUP = 0x0040
MOUSEEVENTF_XDOWN = 0x0080
MOUSEEVENTF_XUP = 0x0100
MOUSEEVENTF_WHEEL = 0x0800
MOUSEEVENTF_HWHEEL = 0x1000
MOUSEEVENTF_ABSOLUTE = 0x8000

WHEEL_DELTA = 120
MAPVK_VK_TO_VSC = 0

MOUSE_BUTTONS = ("left", "right", "middle", "x1", "x2")
_MOUSE_FLAGS = {
    "left": (MOUSEEVENTF_LEFTDOWN, MOUSEEVENTF_LEFTUP, 0),
    "right": (MOUSEEVENTF_RIGHTDOWN, MOUSEEVENTF_RIGHTUP, 0),
    "middle": (MOUSEEVENTF_MIDDLEDOWN, MOUSEEVENTF_MIDDLEUP, 0),
    "x1": (MOUSEEVENTF_XDOWN, MOUSEEVENTF_XUP, 1),
    "x2": (MOUSEEVENTF_XDOWN, MOUSEEVENTF_XUP, 2),
}


class _MOUSEINPUT(ctypes.Structure):
    _fields_ = (
        ("dx", wintypes.LONG),
        ("dy", wintypes.LONG),
        ("mouseData", wintypes.DWORD),
        ("dwFlags", wintypes.DWORD),
        ("time", wintypes.DWORD),
        ("dwExtraInfo", ctypes.c_void_p),
    )


class _KEYBDINPUT(ctypes.Structure):
    _fields_ = (
        ("wVk", wintypes.WORD),
        ("wScan", wintypes.WORD),
        ("dwFlags", wintypes.DWORD),
        ("time", wintypes.DWORD),
        ("dwExtraInfo", ctypes.c_void_p),
    )


class _INPUT(ctypes.Structure):
    class _U(ctypes.Union):
        _fields_ = (("ki", _KEYBDINPUT), ("mi", _MOUSEINPUT))

    _anonymous_ = ("u",)
    _fields_ = (("type", wintypes.DWORD), ("u", _U))


user32.SendInput.argtypes = (wintypes.UINT, ctypes.POINTER(_INPUT), ctypes.c_int)
user32.SendInput.restype = wintypes.UINT
user32.MapVirtualKeyW.argtypes = (wintypes.UINT, wintypes.UINT)
user32.MapVirtualKeyW.restype = wintypes.UINT
user32.GetCursorPos.argtypes = (ctypes.POINTER(wintypes.POINT),)
user32.GetCursorPos.restype = wintypes.BOOL
user32.SetCursorPos.argtypes = (ctypes.c_int, ctypes.c_int)
user32.SetCursorPos.restype = wintypes.BOOL
user32.WindowFromPoint.argtypes = (wintypes.POINT,)
user32.WindowFromPoint.restype = wintypes.HWND
user32.GetWindowThreadProcessId.argtypes = (wintypes.HWND, ctypes.POINTER(wintypes.DWORD))
user32.GetWindowThreadProcessId.restype = wintypes.DWORD
user32.GetForegroundWindow.argtypes = ()
user32.GetForegroundWindow.restype = wintypes.HWND
user32.GetAsyncKeyState.argtypes = (ctypes.c_int,)
user32.GetAsyncKeyState.restype = ctypes.c_short
kernel32.GetCurrentProcessId.argtypes = ()
kernel32.GetCurrentProcessId.restype = wintypes.DWORD
winmm.timeBeginPeriod.argtypes = (wintypes.UINT,)
winmm.timeEndPeriod.argtypes = (wintypes.UINT,)

_send_lock = threading.Lock()


# --- timer -------------------------------------------------------------------

def begin_high_res_timer(period_ms: int = 1) -> None:
    try:
        winmm.timeBeginPeriod(period_ms)
    except Exception:
        pass


def end_high_res_timer(period_ms: int = 1) -> None:
    try:
        winmm.timeEndPeriod(period_ms)
    except Exception:
        pass


# --- low level send ----------------------------------------------------------

def _send(inputs: list[_INPUT]) -> None:
    if not inputs:
        return
    n = len(inputs)
    arr = (_INPUT * n)(*inputs)
    with _send_lock:
        sent = user32.SendInput(n, arr, ctypes.sizeof(_INPUT))
    if sent != n:
        err = ctypes.get_last_error()
        raise OSError(f"SendInput inserted {sent}/{n} events (WinError {err})")


def _kbd(vk: int, up: bool) -> _INPUT:
    scan = user32.MapVirtualKeyW(vk, MAPVK_VK_TO_VSC)
    flags = KEYEVENTF_KEYUP if up else 0
    if vk in keys.EXTENDED_VKS:
        flags |= KEYEVENTF_EXTENDEDKEY
    inp = _INPUT()
    inp.type = INPUT_KEYBOARD
    inp.ki.wVk = vk
    inp.ki.wScan = scan & 0xFF
    inp.ki.dwFlags = flags
    inp.ki.time = 0
    inp.ki.dwExtraInfo = INJECT_TAG
    return inp


def _unicode(code_unit: int, up: bool) -> _INPUT:
    inp = _INPUT()
    inp.type = INPUT_KEYBOARD
    inp.ki.wVk = 0
    inp.ki.wScan = code_unit
    inp.ki.dwFlags = KEYEVENTF_UNICODE | (KEYEVENTF_KEYUP if up else 0)
    inp.ki.time = 0
    inp.ki.dwExtraInfo = INJECT_TAG
    return inp


def _mouse(flags: int, data: int = 0, dx: int = 0, dy: int = 0) -> _INPUT:
    inp = _INPUT()
    inp.type = INPUT_MOUSE
    inp.mi.dx = dx
    inp.mi.dy = dy
    inp.mi.mouseData = ctypes.c_uint32(data & 0xFFFFFFFF).value
    inp.mi.dwFlags = flags
    inp.mi.time = 0
    inp.mi.dwExtraInfo = INJECT_TAG
    return inp


# --- keyboard ---------------------------------------------------------------

def key_down(vk: int) -> None:
    _send([_kbd(vk, False)])


def key_up(vk: int) -> None:
    _send([_kbd(vk, True)])


def tap_key(vk: int) -> None:
    _send([_kbd(vk, False), _kbd(vk, True)])


def chord_down(vks: Iterable[int]) -> None:
    _send([_kbd(vk, False) for vk in vks])


def chord_up(vks: Iterable[int]) -> None:
    _send([_kbd(vk, True) for vk in reversed(list(vks))])


def tap_chord(vks: Iterable[int]) -> None:
    vk_list = list(vks)
    _send([_kbd(vk, False) for vk in vk_list] + [_kbd(vk, True) for vk in reversed(vk_list)])


def release_all_modifiers() -> None:
    """Key-up every modifier; harmless for keys that are not down."""
    inputs = [_kbd(vk, True) for vk in sorted(keys.MODIFIER_VKS)]
    try:
        _send(inputs)
    except OSError:
        pass


def type_text(text: str, char_delay: float = 0.0) -> None:
    """Type arbitrary Unicode text using KEYEVENTF_UNICODE."""
    for ch in text:
        units = ch.encode("utf-16-le")
        code_units = [int.from_bytes(units[i:i + 2], "little") for i in range(0, len(units), 2)]
        if ch == "\n":
            tap_key(keys.VK["enter"])
        else:
            batch: list[_INPUT] = []
            for cu in code_units:
                batch.append(_unicode(cu, False))
            for cu in code_units:
                batch.append(_unicode(cu, True))
            _send(batch)
        if char_delay > 0:
            time.sleep(char_delay)


# --- mouse -------------------------------------------------------------------

def mouse_down(button: str = "left") -> None:
    down, _up, data = _MOUSE_FLAGS[button]
    _send([_mouse(down, data)])


def mouse_up(button: str = "left") -> None:
    _down, up, data = _MOUSE_FLAGS[button]
    _send([_mouse(up, data)])


def click(button: str = "left", count: int = 1) -> None:
    down, up, data = _MOUSE_FLAGS[button]
    _send([_mouse(down, data), _mouse(up, data)] * max(1, count))


def release_all_mouse_buttons() -> None:
    for button in MOUSE_BUTTONS:
        try:
            mouse_up(button)
        except OSError:
            pass


def move_relative(dx: int, dy: int) -> None:
    if dx == 0 and dy == 0:
        return
    _send([_mouse(MOUSEEVENTF_MOVE, 0, int(dx), int(dy))])


def wheel(delta_units: int) -> None:
    """Vertical wheel. ``delta_units`` in 1/120 notch units; + = up."""
    if delta_units:
        _send([_mouse(MOUSEEVENTF_WHEEL, int(delta_units))])


def hwheel(delta_units: int) -> None:
    """Horizontal wheel. + = right."""
    if delta_units:
        _send([_mouse(MOUSEEVENTF_HWHEEL, int(delta_units))])


def get_cursor_pos() -> tuple[int, int]:
    pt = wintypes.POINT()
    user32.GetCursorPos(ctypes.byref(pt))
    return pt.x, pt.y


def set_cursor_pos(x: int, y: int) -> None:
    user32.SetCursorPos(int(x), int(y))


# --- window helpers ----------------------------------------------------------

def pid_at_point(x: int, y: int) -> int:
    hwnd = user32.WindowFromPoint(wintypes.POINT(int(x), int(y)))
    if not hwnd:
        return 0
    pid = wintypes.DWORD()
    user32.GetWindowThreadProcessId(hwnd, ctypes.byref(pid))
    return int(pid.value)


def foreground_pid() -> int:
    hwnd = user32.GetForegroundWindow()
    if not hwnd:
        return 0
    pid = wintypes.DWORD()
    user32.GetWindowThreadProcessId(hwnd, ctypes.byref(pid))
    return int(pid.value)


def current_pid() -> int:
    return int(kernel32.GetCurrentProcessId())


def is_key_physically_down(vk: int) -> bool:
    return bool(user32.GetAsyncKeyState(vk) & 0x8000)
